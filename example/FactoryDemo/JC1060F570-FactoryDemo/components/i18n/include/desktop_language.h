/** @brief Named entry with localized language strings. */
typedef struct {
    const char *key;
    const char *english;
    const char *chinese;
} desktop_language_text_t;

/**
 * @brief 根据字体能力初始化运行时语言。
 * @param chinese_capable Whether a Chinese font is available.
 */
void desktop_language_init(bool chinese_capable);

/**
 * @brief 选择运行时语言；缺少中文字体时拒绝中文。
 * @param language Language to use.
 * @return 选择成功时为 true，缺少中文字体而拒绝时为 false。
 */
bool desktop_language_select(desktop_language_t language);

/** @brief 监听器在请求方任务中执行，以返回值表示是否接受切换。 */
typedef bool (*desktop_language_listener_t)(desktop_language_t language, void *user_data);

/**
 * @brief 注册唯一的语言监听器；传入 NULL 可取消注册。
 * @param listener Listener callback.
 * @param user_data Caller-supplied context.
 */
void desktop_language_register_listener(desktop_language_listener_t listener, void *user_data);

/**
 * @brief 请求切换语言；无监听器或监听器拒绝时返回 false。
 * @param language Language to use.
 * @return 监听器接受切换时为 true，否则为 false。
 */
bool desktop_language_request(desktop_language_t language);

/**
 * @brief 查询调用方报告的中文字体能力。
 * @return 调用方报告中文字体可用时为 true。
 */
bool desktop_language_chinese_available(void);

/**
 * @brief 返回当前运行时语言。
 * @return 当前运行时语言。
 */
desktop_language_t desktop_language_current(void);

/**
 * @brief 借用只读词条；无效键返回 NULL。
 * @param key Key to look up.
 * @return 借用的只读词条，无效键返回 NULL。
 */
const desktop_language_text_t *desktop_language_entry(desktop_text_key_t key);

/**
 * @brief 借用当前语言文本；无效键返回固定占位文本。
 * @param key Key to look up.
 * @return 借用的当前语言文本，无效键返回固定占位文本。
 */
const char *desktop_language_lookup(desktop_text_key_t key);

/**
 * @brief 借用指定语言文本；无效语言回退为英文。
 * @param language Language to use.
 * @param key Key to look up.
 * @return 借用的指定语言文本；无效语言回退为英文。
 */
const char *desktop_language_lookup_for(desktop_language_t language, desktop_text_key_t key);

/**
 * @brief 按名称查找词条键；NULL 或未知名称返回 DESKTOP_TEXT_KEY_COUNT。
 * @param key_name Key name to look up.
 * @return 对应的词条键；名称为 NULL 或未知时返回 DESKTOP_TEXT_KEY_COUNT。
 */
desktop_text_key_t desktop_language_key_from_name(const char *key_name);

/**
 * @brief 借用完整的只读词库，并输出词条数量。
 * @param[out] count 接收词条数量。
 * @return 借用的完整只读词库。
 */
const desktop_language_text_t *desktop_language_catalog(size_t *count);

