static desktop_language_t s_language = DESKTOP_LANGUAGE_ENGLISH;
static bool s_chinese_capable;
static desktop_language_listener_t s_listener;
static void *s_listener_arg;

static bool language_is_valid(desktop_language_t language)
{
    return language == DESKTOP_LANGUAGE_ENGLISH || language == DESKTOP_LANGUAGE_CHINESE;
}

void desktop_language_init(bool chinese_capable)
{
    s_chinese_capable = chinese_capable;
    s_language = chinese_capable ? DESKTOP_LANGUAGE_CHINESE : DESKTOP_LANGUAGE_ENGLISH;
}

/**
 * @brief 校验语言与字体能力后更新当前语言。
 * @param language 要选择的语言。
 * @return 切换成功时返回 true，否则返回 false。
 */
bool desktop_language_select(desktop_language_t language)
{
    if (!language_is_valid(language) ||
        (language == DESKTOP_LANGUAGE_CHINESE && !s_chinese_capable)) {
        return false;
    }
    s_language = language;
    return true;
}

bool desktop_language_chinese_available(void)
{
    return s_chinese_capable;
}

void desktop_language_register_listener(desktop_language_listener_t listener, void *user_data)
{
    s_listener = listener;
    s_listener_arg = listener != NULL ? user_data : NULL;
}

/**
 * @brief 将切换请求同步交给已注册的监听器。
 * @param language 请求切换到的语言。
 * @return 监听器接受请求时返回 true，否则返回 false。
 */
bool desktop_language_request(desktop_language_t language)
{
    if (s_listener == NULL) {
        return false;
    }
    return s_listener(language, s_listener_arg);
}

desktop_language_t desktop_language_current(void)
{
    return s_language;
}

const desktop_language_text_t *desktop_language_entry(desktop_text_key_t key)
{
    if (key < 0 || key >= DESKTOP_TEXT_KEY_COUNT) {
        return NULL;
    }
    return &s_catalog[key];
}

/**
 * @brief 按指定语言读取词条，并处理无效键与语言回退。
 * @param language 查找词条时使用的语言。
 * @param key 要查找的词条键。
 * @return 词条文本；无效语言或词条键返回占位文本。
 */
const char *desktop_language_lookup_for(desktop_language_t language, desktop_text_key_t key)
{
    const desktop_language_text_t *entry = desktop_language_entry(key);
    if (!language_is_valid(language)) {
        return s_catalog[DESKTOP_TEXT_PLACEHOLDER].english;
    }
    if (entry == NULL) {
        return language == DESKTOP_LANGUAGE_CHINESE
                   ? s_catalog[DESKTOP_TEXT_PLACEHOLDER].chinese
                   : s_catalog[DESKTOP_TEXT_PLACEHOLDER].english;
    }
    return language == DESKTOP_LANGUAGE_CHINESE ? entry->chinese : entry->english;
}

const char *desktop_language_lookup(desktop_text_key_t key)
{
    return desktop_language_lookup_for(s_language, key);
}

desktop_text_key_t desktop_language_key_from_name(const char *key_name)
{
    if (key_name == NULL) {
        return DESKTOP_TEXT_KEY_COUNT;
    }
    for (desktop_text_key_t key = 0; key < DESKTOP_TEXT_KEY_COUNT; ++key) {
        if (strcmp(key_name, s_catalog[key].key) == 0) {
            return key;
        }
    }
    return DESKTOP_TEXT_KEY_COUNT;
}

const desktop_language_text_t *desktop_language_catalog(size_t *count)
{
    if (count != NULL) {
        *count = DESKTOP_TEXT_KEY_COUNT;
    }
    return s_catalog;
}
